const byId = new Map(courses.map((course) => [course.id, course]));

/** Resolve an ordered list of course ids into course records. */
export function pickCourses(ids: string[]): Course[] {
  return ids.map((id) => {
    const course = byId.get(id);
    if (!course) throw new Error(`Unknown course id: ${id}`);
    return course;
  });
}

